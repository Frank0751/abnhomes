/**
 * The Cloudflare Worker entry.
 *
 * OpenNext generates a Worker that only answers HTTP requests. This wraps it to
 * add a scheduled handler, which takes over the jobs that ran on Vercel crons
 * and on the GitHub Actions sweeper.
 *
 * The move matters for more than tidiness. GitHub treats schedules as best
 * effort, and the sweeper declared "every 15 minutes" was in practice running
 * every seven hours or so — so a message queued as an instant alert could wait
 * most of a working day. Cloudflare's triggers fire on time.
 *
 * Each schedule calls the existing cron route through the Next.js handler, in
 * process — no network hop and no second implementation. The route still
 * checks CRON_SECRET, exactly as when GitHub calls it.
 */

// @ts-ignore — generated by `opennextjs-cloudflare build`; absent until then.
import { default as handler } from './.open-next/worker.js'

type Env = {
  CRON_SECRET?: string
  CRONS_ENABLED?: string
  [binding: string]: unknown
}

type Context = { waitUntil(promise: Promise<unknown>): void }
type ScheduledEvent = { cron: string; scheduledTime: number }

type NextHandler = {
  fetch(request: Request, env: Env, ctx: Context): Promise<Response>
}

/** Cron expression → the route that does the work. Must match wrangler.jsonc. */
const SCHEDULES: Record<string, string> = {
  '* * * * *': '/api/cron/outbox',
  '0 6 * * *': '/api/cron/rent-run',
  '17 6 * * *': '/api/cron/ical-sync',
  '0 7 * * *': '/api/cron/digest',
}

const next = handler as NextHandler

export default {
  fetch: next.fetch,

  async scheduled(event: ScheduledEvent, env: Env, ctx: Context) {
    // Off until cut-over: see CRONS_ENABLED in wrangler.jsonc.
    if (env.CRONS_ENABLED !== 'true') return

    const path = SCHEDULES[event.cron]
    if (!path) {
      console.error(`[cron] no job registered for "${event.cron}"`)
      return
    }

    const request = new Request(`https://abnhomes.internal${path}`, {
      headers: env.CRON_SECRET ? { authorization: `Bearer ${env.CRON_SECRET}` } : {},
    })

    ctx.waitUntil(
      next.fetch(request, env, ctx).then(async (response) => {
        if (!response.ok) {
          const body = await response.text().catch(() => '')
          console.error(`[cron] ${path} answered ${response.status}: ${body.slice(0, 300)}`)
        }
      })
    )
  },
}
